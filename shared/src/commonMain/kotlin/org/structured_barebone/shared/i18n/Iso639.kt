// Bayrak emoji'si, ISO 3166-1 alpha-2 kodunun Unicode "regional indicator symbol" karsiliklarindan
// uretilir; flag-icons'un CSS sprite yaklasimi Compose'da mevcut olmadigi icin bunun yerine
// isletim sistemi/klavye fontunun native emoji destegine dayanilir. Alt bolge kodlari (orn. "gb-wls")
// icin sadece ilk 2 harf (ana ulke) kullanilir.
fun languageFlagEmoji(countryCode: String?): String? {
    if (countryCode == null) return null
    val base = countryCode.take(2).uppercase()
    if (base.length != 2 || base.any { it !in 'A'..'Z' }) return null
    return base.map { char -> codePointToString(0x1F1E6 + (char - 'A')) }.joinToString("")
}

// java.lang.Character.toChars gibi JVM'e ozgu bir API kullanmadan (bu dosya commonMain'de,
// Android/iOS ikisinde de derlenmesi gerekiyor) supplementary plane (>0xFFFF) bir kod noktasini
// UTF-16 surrogate ciftine elle cevirir.
private fun codePointToString(codePoint: Int): String {
    if (codePoint <= 0xFFFF) return codePoint.toChar().toString()
    val cp = codePoint - 0x10000
    val high = (cp shr 10) + 0xD800
    val low = (cp and 0x3FF) + 0xDC00
    return charArrayOf(high.toChar(), low.toChar()).concatToString()
}
